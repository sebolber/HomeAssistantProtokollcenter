#!/usr/bin/env node
// Iter E1: Generiert frontend/src/utils/findings-i18n.generated.ts aus den
// Backend-translations/*.json. Damit ist das Backend die Single Source of
// Truth fuer Findings-Strings; das Frontend zieht sie aus dem Bundle.
//
// Aufruf:
//   node scripts/generate-findings-i18n.mjs
//
// Validierung:
// - Pro Code muessen ``title``, ``description`` (und ``help_url``) vorhanden
//   sein.
// - Alle Sprachen muessen die gleichen Codes liefern. Fehlt ein Code, wirft
//   das Skript einen Fehler — die CI faengt das.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const TRANS_DIR = join(ROOT, "custom_components/messagehub/translations");
const OUT_FILE = join(ROOT, "frontend/src/utils/findings-i18n.generated.ts");

const langs = readdirSync(TRANS_DIR)
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort();

if (langs.length === 0) {
  console.error("No translation files found in", TRANS_DIR);
  process.exit(1);
}

const data = {};
for (const lang of langs) {
  const fn = join(TRANS_DIR, `${lang}.json`);
  const json = JSON.parse(readFileSync(fn, "utf8"));
  const codes = json?.findings?.codes ?? {};
  data[lang] = codes;
}

// Validierung: alle Sprachen muessen die gleichen Codes haben.
const ref = new Set(Object.keys(data[langs[0]]));
for (const lang of langs) {
  const got = new Set(Object.keys(data[lang]));
  for (const code of ref) {
    if (!got.has(code)) {
      console.error(
        `[E1] Sprache "${lang}" fehlt Code "${code}" (vorhanden in "${langs[0]}")`,
      );
      process.exit(2);
    }
  }
  for (const code of got) {
    if (!ref.has(code)) {
      console.error(
        `[E1] Sprache "${lang}" hat zusaetzlichen Code "${code}", der in "${langs[0]}" fehlt`,
      );
      process.exit(3);
    }
  }
}

const banner = `// AUTO-GENERATED by scripts/generate-findings-i18n.mjs — DO NOT EDIT
//
// Iter E1: Source of truth fuer Findings-Strings ist
// custom_components/messagehub/translations/*.json. Das Generator-Skript
// laeuft als Pre-Build-Step (npm run prebuild) und schreibt diese Datei.
// Hand-edits werden beim naechsten Build ueberschrieben.
//
// Vertrag siehe ../utils/findings-i18n.ts.
`;

const out = [
  banner,
  "",
  "export type Lang = " + langs.map((l) => JSON.stringify(l)).join(" | ") + ";",
  "",
  "export interface CodeStrings {",
  "  title: string;",
  "  description: string;",
  "  help_url: string;",
  "}",
  "",
  "export const STRINGS: Record<Lang, Record<string, CodeStrings>> = " +
    JSON.stringify(data, null, 2) +
    ";",
  "",
  "export const SUPPORTED_LANGS: ReadonlyArray<Lang> = [" +
    langs.map((l) => JSON.stringify(l)).join(", ") +
    "];",
  "",
];

writeFileSync(OUT_FILE, out.join("\n"));
console.log(
  `[E1] generated ${OUT_FILE} with ${Object.keys(data[langs[0]]).length} codes ` +
    `in ${langs.length} languages: ${langs.join(", ")}`,
);
